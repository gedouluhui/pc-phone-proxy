#!/usr/bin/env python3
"""Validate and render the single routing policy used by both clients."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GROUPS = ("domestic", "sensitive", "direct", "ai", "google_ai")
JAVA_NAMES = {
    "domestic": "DOMESTIC",
    "sensitive": "SENSITIVE",
    "direct": "DIRECT",
    "ai": "AI_DOMAINS",
    "google_ai": "GOOGLE_AI_DOMAINS",
}


def load():
    data = json.loads((ROOT / "shared" / "routing-policy.json").read_text(encoding="utf-8"))
    if data.get("schema") != 1:
        raise ValueError("unsupported routing policy schema")
    for key in GROUPS:
        values = data.get(key)
        if not isinstance(values, list) or not values:
            raise ValueError("policy group %s must be a non-empty list" % key)
        if any(not isinstance(value, str) or not value or any(c.isspace() for c in value)
               or ("." not in value and value != "cn") for value in values):
            raise ValueError("policy group %s contains an invalid domain" % key)
    if data.get("udp", {}).get("quic") != "reject":
        raise ValueError("QUIC must be rejected by default")
    if data.get("udp", {}).get("default") != "reject":
        raise ValueError("UDP must be rejected by default")
    if data.get("dns", {}).get("ipv6") != "proxy":
        raise ValueError("IPv6 DNS policy must be proxy")
    return data


def render_python(data):
    lines = ["# Generated by tools/sync_policy.py; do not edit.", "SCHEMA = 1"]
    for key in GROUPS:
        name = JAVA_NAMES[key]
        values = json.dumps(data[key], ensure_ascii=True, separators=(",", ":"))
        lines.append("%s = %s" % (name, values))
    lines.append("UDP_POLICY = " + json.dumps(data["udp"], sort_keys=True))
    lines.append("DNS_POLICY = " + json.dumps(data["dns"], sort_keys=True))
    return "\n".join(lines) + "\n"


def render_java(data):
    lines = [
        "// Generated by tools/sync_policy.py; do not edit.",
        "package com.luhui.phoneproxy;",
        "public final class RoutingPolicy {",
        "  private RoutingPolicy() {}",
        "  public static final int SCHEMA = 1;",
    ]
    for key in GROUPS:
        values = ", ".join(json.dumps(value, ensure_ascii=True) for value in data[key])
        lines.append("  public static final String[] %s = {%s};" % (JAVA_NAMES[key], values))
    lines.append("  public static final String UDP_QUIC = " + json.dumps(data["udp"]["quic"]) + ";")
    lines.append("  public static final String UDP_DEFAULT = " + json.dumps(data["udp"]["default"]) + ";")
    lines.append("  public static final String DNS_IPV6 = " + json.dumps(data["dns"]["ipv6"]) + ";")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        data = load()
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print("policy invalid: %s" % error)
        return 1
    outputs = {
        ROOT / "pc" / "_proxy" / "policy.py": render_python(data),
        ROOT / "phone" / "src" / "com" / "luhui" / "phoneproxy" / "RoutingPolicy.java": render_java(data),
    }
    drift = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if drift:
        print("policy drift: " + ", ".join(drift))
        return 1
    print("policy OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
